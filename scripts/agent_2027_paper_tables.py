"""Generate IEEE manuscript tables from existing committed reports, offline."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'paper/agent2027/generated'
SOURCES = ('paper/agent-2027-routing-evidence.json',
           'reports/agent-2027-differentiation/summary.json',
           'reports/agent-2027-label-error-audit/summary.json')
CASES = tuple(f'reports/mia-bench-failure-decomposition/{m}-cases.jsonl' for m in ('qwen', 'openai', 'anthropic'))
ROUTE = {'B4': 'Direct', 'B5': 'Review'}
EXPECTED = {'ALLOW': 'execute', 'CLARIFY': 'clarify', 'REJECT': 'reject'}
# Stops governed by the time conventions stated in Sec. II-A (by gold reason or by scenario family);
# all others follow from governed-world facts.
CONVENTION_REASONS = {'time_scope_future', 'time_scope_invalid', 'time_scope_incomplete', 'snapshot_point_missing'}
CONVENTION_FAMILIES = {'time_scope_future', 'time_scope_invalid', 'time_scope_missing_start', 'snapshot_point_missing'}


def wilson(k, n, z=1.959963984540054):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return f"{max(0.0, c - h) * 100:.0f}--{min(1.0, c + h) * 100:.0f}"


def load_cases(path):
    rows = [json.loads(l) for l in (ROOT / path).read_text().splitlines() if l.strip()]
    return [r for r in rows if r.get('authority_unit')]


def rules_route(units):
    allow = sum(r['gold_decision'] == 'ALLOW' and r['candidate_oracle_decision'] == 'ALLOW' for r in units)
    unsafe = sum(r['gold_decision'] != 'ALLOW' and r['candidate_oracle_decision'] == 'ALLOW' for r in units)
    exact = sum(r['candidate_oracle_decision'] == r['gold_decision'] for r in units)
    fail = sum(r['candidate_oracle_decision'] is None for r in units)
    return allow, unsafe, exact, fail


def is_time_rule(r):
    return bool(set(r['gold_reasons']) & CONVENTION_REASONS) or r['taxonomy_family'] in CONVENTION_FAMILIES


def error_types(units, decide):
    out = {'gov': 0, 'conv': 0, 'wrong': 0, 'allow': 0, 'fail': 0}
    for r in units:
        act, gold = decide(r), r['gold_decision']
        if act == EXPECTED[gold]:
            continue
        if act in ('failure', 'terminal_failure'):
            out['fail'] += 1
        elif gold == 'ALLOW':
            out['allow'] += 1
        elif act == 'execute':
            out['conv' if is_time_rule(r) else 'gov'] += 1
        else:
            out['wrong'] += 1
    return out


def table(caption, label, spec, header, rows):
    return ('% Generated by scripts/agent_2027_paper_tables.py; do not hand-edit.\n'
            '\\begin{table}[t]\n\\centering\n\\caption{' + caption + '}\n\\label{tab:' + label + '}\n'
            '{\\small\n\\begin{tabular}{' + spec + '}\n\\toprule\n' + header + ' \\\\\n\\midrule\n' +
            '\n'.join(' & '.join(map(str, r)) + ' \\\\' for r in rows) +
            '\n\\bottomrule\n\\end{tabular}\n}\n\\end{table}\n')


def wide_table(caption, label, spec, header, rows):
    return ('% Generated by scripts/agent_2027_paper_tables.py; do not hand-edit.\n'
            '\\begin{table*}[t]\n\\centering\n\\caption{' + caption + '}\n\\label{tab:' + label + '}\n'
            '{\\small\n\\begin{tabular}{' + spec + '}\n\\toprule\n' + header + ' \\\\\n\\midrule\n' +
            '\n'.join(' & '.join(map(str, r)) + ' \\\\' for r in rows) +
            '\n\\bottomrule\n\\end{tabular}\n}\n\\end{table*}\n')


def metrics(units, decide):
    allow = sum(u['gold_decision'] == 'ALLOW' and decide(u) == 'execute' for u in units)
    stop = sum(u['gold_decision'] != 'ALLOW' and decide(u) == 'execute' for u in units)
    exact = sum(decide(u) == EXPECTED[u['gold_decision']] for u in units)
    return allow, stop, exact


RULE_ACTION = {'ALLOW': 'execute', 'CLARIFY': 'clarify', 'REJECT': 'reject', None: 'failure'}


def fail_closed(first, second):
    """Execute only if both components execute; otherwise reject beats clarify (Sec. II-A)."""
    if first == 'execute' and second == 'execute':
        return 'execute'
    acts = {first, second}
    if 'reject' in acts:
        return 'reject'
    if 'clarify' in acts:
        return 'clarify'
    return 'failure'


def derive():
    routing, diff, errors = [json.loads((ROOT / p).read_text()) for p in SOURCES]
    pairs, disagreements, kinds, fails = [], [], [], {}
    route_rows = {name: ['\\emph{' + name + '}'] for name in ('Direct', 'Review', 'Rules$^*$', 'Direct+Rules$^*$', 'MIA', 'Direct+MIA')}
    for model, case_path in zip(('Qwen', 'OpenAI', 'Anthropic'), CASES):
        data = routing['holdout'][model]
        units = load_cases(case_path)
        if len(units) != 101:
            raise ValueError('authority population differs')
        for route in ('B4', 'B5'):
            r = data['systems'][route]
            a, u, e = metrics(units, lambda x, route=route: x['actions'][route])
            if (a, u, e) != (r['allow_executes'], r['unsafe_executes'], r['three_way_correct']):
                raise ValueError('case files and routing report disagree')
            route_rows[ROUTE[route]] += [a, u, wilson(u, 64), e]
            fails[(model, ROUTE[route])] = r['terminal_failures']
        rules = lambda x: RULE_ACTION[x['candidate_oracle_decision']]
        a, u, e = metrics(units, rules)
        if (a, u, e) != rules_route(units)[:3]:
            raise ValueError('rules route mismatch')
        route_rows['Rules$^*$'] += [a, u, wilson(u, 64), e]
        fails[(model, 'Rules')] = rules_route(units)[3]
        both = lambda x: fail_closed(x['actions']['B4'], rules(x))
        a, u, e = metrics(units, both)
        route_rows['Direct+Rules$^*$'] += [a, u, wilson(u, 64), e]
        a, u, e = metrics(units, lambda x: x['actions']['MIA'])
        route_rows['MIA'] += [a, u, wilson(u, 64), e]
        a, u, e = metrics(units, lambda x: fail_closed(x['actions']['B4'], x['actions']['MIA']))
        route_rows['Direct+MIA'] += [a, u, wilson(u, 64), e]
        fails[(model, 'MIA gaps')] = sum(x['actions']['MIA'] == 'coverage_gap' for x in units)
        for label, decide in (('Direct', lambda x: x['actions']['B4']), ('Rules$^*$', rules)):
            t = error_types(units, decide)
            kinds.append([model if label == 'Direct' else '', label, t['gov'], t['conv'], t['wrong'], t['allow'], t['fail']])
        p = routing['governance_pairs']['models'][model]
        pairs.append([model] + [p[r][k] for k in ('binary_both_correct', 'three_way_both_correct') for r in ('B4','B5')])
        d = data['disagreements']
        disagreements.append([model, d['disagreements']] + [d['outcomes'].get(k, 0) for k in ('b4_only_correct','b5_only_correct','neither_correct')])
    labels = {'principal access':'Principal access', 'certification':'Certification',
              'relationship path':'Relationship path', 'aggregation safety (fanout)':'Aggregation grain',
              'required context (FX)':'FX context'}
    changes = [[labels[r['change']], r['pairs']] + [f"{r['routes'][m]['B4']['both_exact']}/{r['routes'][m]['B5']['both_exact']}" for m in ('qwen','openai','anthropic')]
               for r in diff['authority_pairs']['by_change']]
    quality = list(route_rows.values())
    if {k: v for k, v in fails.items() if v and k[1] != 'MIA gaps'} != {('Anthropic', 'Review'): 5, ('Anthropic', 'Rules'): 5}:
        raise ValueError('technical-failure note in Table I caption is stale')
    # Reconcile the complete census against the routing endpoints before typesetting.
    for m, name in zip(('qwen','openai','anthropic'),('Qwen','OpenAI','Anthropic')):
        if errors['models'][m]['exact_errors'] != 101-routing['holdout'][name]['systems']['B4']['three_way_correct']:
            raise ValueError('complete B4 census and routing report disagree')
    files = {
        'quality.tex': wide_table('Holdout decisions (37 ALLOW, 64 should-stop per model). ALLOW/Stop: requests executed; nominal Wilson 95\\% intervals assume independent cases. Exact: correct three-way actions; failures and MIA gaps count as errors (five Anthropic cases lack a candidate). Combined routes execute only if both components do; otherwise reject beats clarify. $^*$Oracle upper bounds using the label-defining rules. MIA has coverage gaps on ' + '/'.join(str(fails[(m, 'MIA gaps')]) for m in ('Qwen', 'OpenAI', 'Anthropic')) + ' cases.', 'quality', 'l' + 'rrrr' * 3, ' & \\multicolumn{4}{c}{Qwen} & \\multicolumn{4}{c}{OpenAI} & \\multicolumn{4}{c}{Anthropic} \\\\\n\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}\\cmidrule(lr){10-13}\nRoute' + ' & ALLOW & Stop & 95\\% CI & Exact' * 3, quality),
        'kinds.tex': table('Errors of Direct and Rules by type. Executions of requests that should stop are split by whether the stop follows from a governed-world fact or from a time rule (supplied clock, interval bounds or snapshot timing). Fail: no valid interpreter candidate.', 'kinds', '@{}llrrrrr@{}', 'Model & Route & \\shortstack{Exec.\\\\fact} & \\shortstack{Exec.\\\\time} & \\shortstack{Wrong\\\\stop} & \\shortstack{ALLOW\\\\stop} & Fail', kinds),
        'pairs.tex': table('Both decisions correct in each of 15 authority pairs. Binary is execute/stop; exact distinguishes all three actions. Only 14 pairs require a binary flip.', 'pairs', 'lrrrr', 'Model & \\shortstack{Direct\\\\binary} & \\shortstack{Review\\\\binary} & \\shortstack{Direct\\\\exact} & \\shortstack{Review\\\\exact}', pairs),
        'changes.tex': table('Authority-pair correctness by changed governance fact. Entries are Direct/Review exact-correct pairs; n is the category size.', 'changes', 'lrrrr', 'Change & n & Qwen & OpenAI & Anthropic', changes),
        'disagreements.tex': table('All holdout disagreements between Direct and Review, by which route matches the gold action.', 'disagreements', 'lrrrr', 'Model & Total & \\shortstack{Only Direct\\\\correct} & \\shortstack{Only Review\\\\correct} & Neither', disagreements),
    }
    provenance = {'inputs_sha256': {p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in SOURCES + CASES},
                  'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  'role':'typesetting of committed descriptive evidence; no inference'}
    files['provenance.json'] = json.dumps(provenance, indent=2, sort_keys=True)+'\n'
    return files


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    for name, content in derive().items():
        path=OUT/name
        if args.check:
            if path.read_text()!=content:
                raise ValueError(f'{path} differs from regenerated table')
        else:
            OUT.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
    print('AGENT paper tables verified' if args.check else 'AGENT paper tables generated')

if __name__=='__main__':
    main()
